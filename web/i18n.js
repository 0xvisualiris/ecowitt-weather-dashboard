// The visitor's language and every text the page shows, in English and German.
//
// The language is chosen per visitor on the settings page and kept in their
// browser; without a choice it follows the browser's language. A change reloads
// the page, so every module can read LANG and call tr() once, at load time.
// This file is the only place in the frontend with German text.

const KEY = 'wetterstation.lang';
export const LANGUAGES = { en: 'English', de: 'Deutsch' };

function initial() {
  try { const saved = localStorage.getItem(KEY); if (saved in LANGUAGES) return saved; } catch { /* private mode */ }
  return /^de\b/i.test(navigator.language || '') ? 'de' : 'en';
}

export const LANG = initial();
// en-GB: 24-hour clock and day-month order, which fit metric weather data.
export const LOCALE = LANG === 'de' ? 'de-DE' : 'en-GB';
export const DECIMAL = LANG === 'de' ? ',' : '.';

export function setLang(lang) {
  try { localStorage.setItem(KEY, lang); } catch { /* private mode */ }
  location.reload();
}

// tr('key', { name: 'value' }) → the text in the visitor's language, with {name} filled in.
export function tr(key, vars) {
  const text = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
  if (typeof text === 'function') return text(vars ?? {});
  return vars ? text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : text;
}

// A text from the server: a plain string (shown as written), or one per language ({ en, de }).
export function loc(text) {
  if (text == null || typeof text !== 'object') return text ?? '';
  return text[LANG] ?? text.en ?? Object.values(text)[0] ?? '';
}

// Fills in every element marked data-t="key", and data-t-<attribute>="key" for attributes. It runs
// once, at the end of this module, as soon as it loads: before any view fetches data and writes its own text
// into those elements, so the static texts never overwrite live ones.
function translatePage() {
  document.documentElement.lang = LANG;
  for (const node of document.querySelectorAll('[data-t]')) node.textContent = tr(node.dataset.t);
  for (const node of document.querySelectorAll('[data-t-aria-label]')) node.setAttribute('aria-label', tr(node.dataset.tAriaLabel));
  for (const node of document.querySelectorAll('[data-t-aria-valuetext]')) node.setAttribute('aria-valuetext', tr(node.dataset.tAriaValuetext));
}

// The server says the common admin errors in English; German visitors read them in German.
export function serverError(message) {
  if (LANG !== 'de') return message;
  const tooLong = /^(.+) is too long \(max (\d+) characters\)$/.exec(message);
  if (tooLong) return `${STRINGS.de[`field.${tooLong[1]}`] ?? tooLong[1]} ist zu lang (höchstens ${tooLong[2]} Zeichen).`;
  return STRINGS.de[`error.${message}`] ?? message;
}

